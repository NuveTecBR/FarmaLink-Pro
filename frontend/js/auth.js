export async function apiFetch(url, options = {}) {
  const opts = {
    credentials: "same-origin",
    headers: {
      "Content-Type": "application/json",
      "X-Requested-With": "FarmaLinkHttpRequest",
      ...(options.headers || {}),
    },
    ...options,
  };
  if (opts.body && typeof opts.body === "object") {
    opts.body = JSON.stringify(opts.body);
  }
  const res = await fetch(url, opts);
  const data = await res.json().catch(() => ({}));
  if (!res.ok) {
    const msg = data.campos?.length
      ? data.campos.map((c) => c.mensagem).join(" ")
      : data.erro || `Erro HTTP ${res.status}`;
    const err = new Error(msg);
    err.status = res.status;
    err.data = data;
    throw err;
  }
  return data;
}

export function toast(mensagem, tipo = "ok") {
  let box = document.getElementById("toast-container");
  if (!box) {
    box = document.createElement("div");
    box.id = "toast-container";
    box.className = "toast-container";
    box.setAttribute("aria-live", "polite");
    document.body.appendChild(box);
  }
  const el = document.createElement("div");
  el.className = `toast ${tipo === "erro" ? "toast-error" : ""}`;
  el.textContent = mensagem;
  box.appendChild(el);
  setTimeout(() => el.remove(), 4500);
}

export function aplicarTema(tema) {
  const t = tema === "light" ? "light" : "dark";
  document.documentElement.setAttribute("data-theme", t);
  localStorage.setItem("fl_theme", t);
}

export function alternarAltoContraste() {
  const atual = document.documentElement.getAttribute("data-contrast") === "high";
  if (atual) {
    document.documentElement.removeAttribute("data-contrast");
    localStorage.setItem("fl_contrast", "normal");
  } else {
    document.documentElement.setAttribute("data-contrast", "high");
    localStorage.setItem("fl_contrast", "high");
  }
}

export function carregarTemaInicial() {
  const salvo = localStorage.getItem("fl_theme") || "light";
  aplicarTema(salvo);
  if (localStorage.getItem("fl_contrast") === "high") {
    document.documentElement.setAttribute("data-contrast", "high");
  }
}

/**
 * Focus Trap WCAG 2.1 AA para Modais: mantém Tab/Shift+Tab dentro do modal aberto e foca o primeiro elemento.
 */
export function ativarFocusTrap(modalElement) {
  if (!modalElement) return;
  const seletores = 'button, [href], input, select, textarea, [tabindex]:not([tabindex="-1"])';
  const focaveis = [...modalElement.querySelectorAll(seletores)].filter((el) => !el.disabled && !el.classList.contains("hidden"));
  if (!focaveis.length) return;
  const primeiro = focaveis[0];
  const ultimo = focaveis[focaveis.length - 1];
  primeiro.focus();

  modalElement.onkeydown = (e) => {
    if (e.key !== "Tab") return;
    if (e.shiftKey && document.activeElement === primeiro) {
      e.preventDefault();
      ultimo.focus();
    } else if (!e.shiftKey && document.activeElement === ultimo) {
      e.preventDefault();
      primeiro.focus();
    }
  };
}

export function inicializarCookieBanner() {
  if (localStorage.getItem("fl_lgpd_cookies") === "ok") return;
  const bar = document.getElementById("cookie-banner");
  if (!bar) return;
  bar.classList.remove("hidden");
  document.getElementById("btn-aceitar-cookies")?.addEventListener("click", () => {
    localStorage.setItem("fl_lgpd_cookies", "ok");
    bar.classList.add("hidden");
  });
}
